import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { label, text } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY not configured");

    const systemPrompt = `You are Jeeves, the Phototheology AI assistant. You are a brilliant, warm Bible scholar who thinks through the lens of the Phototheology Palace system (8 floors, rooms, cycles, heavens, ascensions, expansions).

When given a biblical insight or pattern, you must:
1. **Complete the thought** — fully expand on the pattern with all relevant Scripture references (book, chapter, verse)
2. **Trace the pattern** across Scripture showing how it develops and deepens
3. **Connect to Christ** — show how the pattern ultimately points to Jesus
4. **Tag PT rooms** — mention which Palace rooms are activated (e.g., Patterns Room PRm, Parallels P‖, Concentration CR, Types ST)
5. **Surface gems** — highlight 2-3 striking insights that emerge

Format with markdown. Use headers, bold for emphasis, and Scripture references. Keep it thorough but readable — like a passionate teacher who can't stop because the connections keep flowing. Aim for 400-600 words.`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user", content: `Expand on this biblical insight titled "${label}":\n\n"${text}"\n\nComplete the thought. Trace the full pattern across Scripture. Show every connection. Tag the Palace rooms activated.` },
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      const status = response.status;
      if (status === 429) {
        return new Response(JSON.stringify({ error: "Rate limited. Please try again shortly." }), {
          status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (status === 402) {
        return new Response(JSON.stringify({ error: "Credits exhausted." }), {
          status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI error:", status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("banner-deep-dive error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
